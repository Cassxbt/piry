import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { Abi } from "viem";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const target = join(root, "app", "src", "abi", "generated.ts");

const contracts = [
  ["computeMarketAbi", "ComputeMarket.sol/ComputeMarket.json"],
  ["claimTokenAbi", "ClaimToken.sol/ClaimToken.json"],
  ["settlementReceiverAbi", "SettlementReceiver.sol/SettlementReceiver.json"],
  ["simulationReceiverAbi", "SimulationSettlementReceiver.sol/SimulationSettlementReceiver.json"],
  ["markFeedAbi", "PiryMarkFeed.sol/PiryMarkFeed.json"],
] as const;

const entries: string[] = [];
for (const [name, path] of contracts) {
  const file = join(root, "out", path);
  if (!existsSync(file)) throw new Error(`Missing artifact out/${path}. Run \`forge build\` in the repo root first.`);
  const { abi } = JSON.parse(await readFile(file, "utf8")) as { abi: Abi };
  entries.push(`export const ${name} = ${JSON.stringify(abi, null, 2)} as const;`);
}

await mkdir(dirname(target), { recursive: true });
await writeFile(target, `// Generated by scripts/sync-abi.ts from out/. Rerun \`npm run sync-abi\` after \`forge build\`.\n${entries.join("\n\n")}\n`);
console.log(`wrote ${contracts.length} ABIs to src/abi/generated.ts`);
